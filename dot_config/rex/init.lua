-- Migrated from ~/.tmux.conf (prefix ctrl+b).
rex.bind("ctrl+b>ctrl+b", "pane.send_key", { key = "ctrl+b" })

rex.bind("ctrl+b>c", "client.tab.new")
rex.bind("ctrl+b>p", "client.tab.previous")
rex.bind("ctrl+b>n", "client.tab.next")
rex.bind("ctrl+b>shift+w", "client.tab.rename")
rex.bind("ctrl+b>shift+\\", "pane.split", { direction = "right" })
rex.bind("ctrl+b>-", "pane.split", { direction = "down" })
rex.bind("ctrl+b>h", "pane.focus", { direction = "left" })
rex.bind("ctrl+b>j", "pane.focus", { direction = "down" })
rex.bind("ctrl+b>k", "pane.focus", { direction = "up" })
rex.bind("ctrl+b>l", "pane.focus", { direction = "right" })
rex.bind("ctrl+b>shift+h", "pane.resize", { amount = 10, direction = "left" })
rex.bind("ctrl+b>shift+j", "pane.resize", { amount = 10, direction = "down" })
rex.bind("ctrl+b>shift+k", "pane.resize", { amount = 10, direction = "up" })
rex.bind("ctrl+b>shift+l", "pane.resize", { amount = 10, direction = "right" })
rex.bind("ctrl+b>q", "pane.close")
rex.bind("ctrl+b>s", "session.switch")

-- tmux bind -r: repeat mode, entered with ctrl+b then r.
rex.mode("repeat", { exclusive = true })
rex.bind("ctrl+b>r", "client.mode.enter", { name = "repeat" })
rex.bind("repeat/enter", "client.mode.exit")
rex.bind("repeat/escape", "client.mode.exit")
rex.bind("repeat/shift+h", "pane.resize", { amount = 10, direction = "left" })
rex.bind("repeat/shift+j", "pane.resize", { amount = 10, direction = "down" })
rex.bind("repeat/shift+k", "pane.resize", { amount = 10, direction = "up" })
rex.bind("repeat/shift+l", "pane.resize", { amount = 10, direction = "right" })
